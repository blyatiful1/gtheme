def test_error_names_map_onto_the_closed_set_and_never_onto_message_text():
    cases = {
        "org.gnome.Shell.Extensions.Error.NotAllowed": ShellErrorKind.NOT_ALLOWED,
        "org.gnome.Shell.Extensions.Error.DownloadFailed": ShellErrorKind.DOWNLOAD_FAILED,
        "org.gnome.Shell.Extensions.Error.InfoDownloadFailed": ShellErrorKind.DOWNLOAD_FAILED,
        "org.gnome.Shell.Extensions.Error.ExtractFailed": ShellErrorKind.EXTRACT_FAILED,
        "org.gnome.Shell.Extensions.Error.EnableFailed": ShellErrorKind.ENABLE_FAILED,
        "org.freedesktop.DBus.Error.NoReply": ShellErrorKind.NO_REPLY,
        "org.freedesktop.DBus.Error.ServiceUnknown": ShellErrorKind.UNAVAILABLE,
        "com.example.Whatever": ShellErrorKind.OTHER,
    }
    for name, kind in cases.items():
        assert ShellError.from_dbus_name(name, "boom").kind is kind


# -- the pre-armed watcher -------------------------------------------------


def test_the_watcher_only_hears_about_its_own_add_on():
    service, proxy = shell()
    watcher = StateWatcher(uuid="mine@x", shell=service)
    watcher.arm()
    proxy.emit_state("someone-else@y", info("someone-else@y"))
    assert watcher.seen == []
    proxy.emit_state("mine@x", info("mine@x", state=8.0))
    proxy.emit_state("mine@x", info("mine@x", state=1.0))
    assert watcher.seen == [ExtensionState.ACTIVATING, ExtensionState.ACTIVE]
    assert watcher.became_active is True


def test_disarming_stops_the_watcher():
    service, proxy = shell()
    watcher = StateWatcher(uuid="mine@x", shell=service)
    watcher.arm()
    watcher.disarm()
    proxy.emit_state("mine@x", info("mine@x"))
    assert watcher.seen == []
