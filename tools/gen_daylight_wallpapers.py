TARGETS: dict[str, tuple[dict, Path]] = {
    "daybreak": (DAYBREAK, Path("themes/daybreak/wallpaper/daybreak-first-light.png")),
    "hearth": (HEARTH, Path("themes/hearth/wallpaper/hearth-firelight.png")),
}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "which",
        nargs="?",
        choices=sorted(TARGETS),
        help="draw only one of them (default: both)",
    )
    args = parser.parse_args(argv)

    wanted = [args.which] if args.which else sorted(TARGETS)
    for name in wanted:
        recipe, relative = TARGETS[name]
        out = REPO_ROOT / relative
        out.parent.mkdir(parents=True, exist_ok=True)
        _to_png(_draw(**recipe)).save(out, format="PNG", optimize=True)
        print(f"wrote {relative} ({out.stat().st_size // 1024} KiB)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
